export function getDemoPdf(name: string): Buffer | null {
  const lines = DEMO_PDF_LINES[name];
  if (lines) return buildDemoPdf(lines);
  // Generic placeholder for any generated demo doc (CV / cover letter) so the
  // library previews never 404 in demo mode.
  if (/^demo-(cv|cover)-.+\.pdf$/i.test(name)) {
    const kind = /^demo-cover-/i.test(name) ? "Cover letter" : "CV";
    return buildDemoPdf([
      `${kind} (demo)`,
      name,
      "",
      "Fictional placeholder generated by the career-ops-web demo.",
      "No real document content is shipped.",
    ]);
  }
  return null;
}

